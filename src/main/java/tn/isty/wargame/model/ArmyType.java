package tn.isty.wargame.model;

/**
 * Enumération représentant les différents types d’armées disponibles
 * dans le jeu Wargame. Chaque valeur correspond à une nation
 * jouable, avec ses propres unités et caractéristiques.
 */
public enum ArmyType {
    /** Armée française – unités équilibrées, bon moral, défense correcte. */
    FRANCE,

    /** Armée allemande – unités puissantes et robustes, mais plus lentes. */
    ALLEMAGNE,

    /** Armée britannique – unités rapides, spécialisés dans le tir à distance. */
    ROYAUME_UNI
}
